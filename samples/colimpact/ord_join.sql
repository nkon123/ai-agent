-- 컬럼 영향도 평가용 가짜 소스. TOTAL_AMT 는 IF_ORDER_TMP 와 ORD_HDR 양쪽에 있다.
CREATE OR REPLACE PROCEDURE ORD_SYNC AS
BEGIN
  INSERT INTO ORD_HDR (ORD_NO, TOTAL_AMT)
  SELECT T.ORD_NO, T.TOTAL_AMT
    FROM IF_ORDER_TMP T
   WHERE T.STATUS = 'N';

  UPDATE IF_ORDER_TMP
     SET TOTAL_AMT = 0
   WHERE STATUS = 'E';

  SELECT B.TOTAL_AMT
    INTO v_hdr_amt
    FROM IF_ORDER_TMP A
    JOIN ORD_HDR B ON B.ORD_NO = A.ORD_NO
   WHERE A.ORD_NO = p_ord_no;

  UPDATE ORD_HDR
     SET TOTAL_AMT = TOTAL_AMT + 1
   WHERE ORD_NO = p_ord_no;
END;
